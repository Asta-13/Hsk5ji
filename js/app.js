  function pySeg(s){
    var memo={};
    function go(k,first){
      var key=k+'|'+first;if(memo[key]!==undefined)return memo[key];
      if(k===s.length)return (memo[key]={c:0,a:[]});
      var best=null,rest=s.slice(k);
      PY_INIT.concat(['']).forEach(function(ini){
        if(ini&&rest.indexOf(ini)!==0)return;
        var r2=rest.slice(ini.length);
        PY_FIN.forEach(function(fin){
          if(r2.indexOf(fin)!==0)return;
          var sub=go(k+ini.length+fin.length,false);if(!sub)return;
          var c=1+sub.c+((!ini&&!first)?10:0);
          if(!best||c<best.c)best={c:c,a:[[ini,fin]].concat(sub.a)};
        });
      });
      return (memo[key]=best||null);
    }
    return go(0,true);
  }
